    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        userName = name.getText();
        String validSize = String.valueOf(size.getText());
        if(userName.equals("Enter you name")){
            JOptionPane.showMessageDialog(null, "Please enter a username.","Instruction!",JOptionPane.INFORMATION_MESSAGE);
        }else if(validSize.equals("Enter size") || Integer.valueOf(validSize) <= 0)
        {
            JOptionPane.showMessageDialog(null, "Please enter a valid size.","Instruction!",JOptionPane.INFORMATION_MESSAGE);
        }else{
          checkAnswer = true;
        int gameSize = Integer.parseInt(size.getText());
        gameLogic = new SudokuLogic1(gameSize);
        gameGrid.setSize(656, 511);
        gameGrid.removeAll();
        size.setBackground(Color.white);
        gameGrid.setLayout(new GridLayout(gameSize, gameSize, 2, 2));
        comp = new JTextField[gameSize][gameSize];
        for(int i = 0; i < gameSize; i++){
            for(int j = 0; j < gameSize; j++){
                JTextField elements  = new JTextField();
                gameGrid.add(elements);
                elements.setHorizontalAlignment(JTextField.CENTER);
                elements.setFont(new Font("Serif", Font.BOLD, 20));
                if(gameLogic.elements[i][j].isBlank()){
                    elements.setText("?");
                }else{
                   elements.setText(String.valueOf(gameLogic.elements[i][j]));
                   elements.setBackground(new Color(204,255,204));
                   elements.setEditable(false);
                }
                comp[i][j] = elements;
            }
        }
        gameGrid.validate();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

