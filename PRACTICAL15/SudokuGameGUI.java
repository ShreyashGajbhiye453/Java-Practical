    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if(checkAnswer){
        boolean isFill = false;
        answer = new String[gameLogic.size][gameLogic.size];
        for(int i = 0; i < gameLogic.size;i++){
            for(int j = 0; j < gameLogic.size; j++){
                if(comp[i][j].getText().equals("?")){
                    JOptionPane.showMessageDialog(null, "Please fill the remaining answer!", "Complete the Answer!",JOptionPane.INFORMATION_MESSAGE);
                    isFill = true;
                    break;
                }else{
                    answer[i][j] = comp[i][j].getText();
                }
            }
            if(isFill)break;
        }
        boolean ans = gameLogic.checkingCorrect(answer);
        if(ans){
            JOptionPane.showMessageDialog(null, "Congratulations! "+ userName+" played a great game!Hope you enjoyed a lot during playing the game.Play for learning and enjoyment.","Winning Message...",JOptionPane.INFORMATION_MESSAGE);   
            JOptionPane.showMessageDialog(null, "Enter new size and enjoy the new game.", "Play Again",JOptionPane.INFORMATION_MESSAGE);
        size.setBackground(new Color(255,127,127));
        }else{
            JOptionPane.showMessageDialog(null, "Fine, " +userName +" This game is a great opportunity to learn and grow. Let's analyze what we can improve and apply those lessons to our next game.", "Loss Message...",JOptionPane.INFORMATION_MESSAGE); 
            JOptionPane.showMessageDialog(null, "Enter new size and try again new game.", "Play Again",JOptionPane.INFORMATION_MESSAGE);
        size.setBackground(new Color(255,127,127));
        } 
        }else{
            JOptionPane.showMessageDialog(null, "First generate and solve the sudoku.", "Play Firstly.",JOptionPane.INFORMATION_MESSAGE); 
        }
    }//GEN-LAST:event_jButton2ActionPerformed

